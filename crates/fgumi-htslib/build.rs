fn copy_dir(src: &Path, dst: &Path) {
    fs::create_dir_all(dst).unwrap();
    for e in fs::read_dir(src).unwrap() {
        let e = e.unwrap();
        let to = dst.join(e.file_name());
        if e.file_type().unwrap().is_dir() {
            copy_dir(&e.path(), &to);
        } else {
            fs::copy(e.path(), &to).unwrap();
        }
    }
}

/// The headers htslib's configure / Makefile would generate.
fn write_generated_headers(hts: &Path, config: &[&str]) {
    {
        let mut f = fs::File::create(hts.join("config.h")).unwrap();
        for l in config {
            writeln!(f, "{l}").unwrap();
        }
    }
    fs::write(hts.join("version.h"), "#define HTS_VERSION_TEXT \"1.23-fgumi\"\n").unwrap();
    fs::write(
        hts.join("htscodecs/htscodecs/version.h"),
        "#define HTSCODECS_VERSION_TEXT \"1.6.5\"\n",
    )
    .unwrap();
    fs::write(
        hts.join("config_vars.h"),
        "#define HTS_CC \"cc\"\n#define HTS_CPPFLAGS \"\"\n#define HTS_CFLAGS \"\"\n\
         #define HTS_LDFLAGS \"\"\n#define HTS_LIBS \"-ldeflate -lz -lbz2 -llzma\"\n",
    )
    .unwrap();
}

fn main() {
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let src = PathBuf::from("vendor/htslib");
    let hts = out.join("htslib");
    if hts.exists() {
        fs::remove_dir_all(&hts).unwrap();
    }
    copy_dir(&src, &hts);
    println!("cargo:rerun-if-changed=vendor/htslib");
    println!("cargo:rerun-if-changed=csrc/fgumi_hts.c");

    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap();
    let target_arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap();

    let mut config = vec![
        "/* config.h generated by fgumi-htslib build.rs */",
        "#define HAVE_LIBZ 1",
        "#define HAVE_LIBDEFLATE 1",
        "#define HAVE_LIBBZ2 1",
        "#define HAVE_LIBLZMA 1",
        "#define HAVE_LZMA_H 1",
        "#define HAVE_DRAND48 1",
        "#define HAVE_FSYNC 1",
        "#define HAVE_GETPAGESIZE 1",
        "#define HAVE_GMTIME_R 1",
        "#define HAVE_MMAP 1",
        "#define HAVE_POSIX_MEMALIGN 1",
        "#define HAVE_ATTRIBUTE_CONSTRUCTOR 1",
        "#define HAVE_CLOCK_GETTIME_CPUTIME 1",
    ];
    if target_os == "linux" {
        config.push("#define _XOPEN_SOURCE 700");
        config.push("#define _DEFAULT_SOURCE 1");
    }

    let mut cfg = cc::Build::new();
    cfg.warnings(false).pic(true).opt_level(3).include(&hts);
    if let Ok(inc) = env::var("DEP_LIBDEFLATE_INCLUDE") {
        cfg.include(inc);
    }
    for dep in ["DEP_BZIP2_INCLUDE", "DEP_LZMA_INCLUDE"] {
        let inc = env::var(dep).unwrap_or_else(|_| panic!("{dep} not set by its -sys crate"));
        cfg.include(inc);
    }
    if let Ok(inc) = env::var("DEP_Z_INCLUDE") {
        for p in inc.split(',') {
            cfg.include(p);
        }
    }
    // htscodecs SIMD rANS variants, as the htslib Makefile builds them: on
    // x86_64 each variant is compiled with its own instruction-set flags and
    // chosen at run time by cpuid, so the binary runs on any x86_64 CPU and
    // uses AVX2/AVX-512 where present. (aarch64 NEON needs no extra flags.)
    let simd: &[(&str, &[&str])] = if target_arch == "x86_64" {
        config.extend([
            "#define HAVE_DECL___CPUID_COUNT 1",
            "#define HAVE_DECL___GET_CPUID_MAX 1",
            "#define HAVE_SSSE3 1",
            "#define HAVE_POPCNT 1",
            "#define HAVE_SSE4_1 1",
            "#define HAVE_AVX2 1",
            "#define HAVE_AVX512 1",
        ]);
        &[
            ("htscodecs/htscodecs/rANS_static32x16pr_sse4.c", &["-msse4.1", "-mssse3", "-mpopcnt"]),
            ("htscodecs/htscodecs/rANS_static32x16pr_avx2.c", &["-mavx2", "-mpopcnt"]),
            ("htscodecs/htscodecs/rANS_static32x16pr_avx512.c", &["-mavx512f", "-mpopcnt"]),
        ]
    } else {
        config.extend(["#define HAVE_DECL___CPUID_COUNT 0", "#define HAVE_DECL___GET_CPUID_MAX 0"]);
        &[]
    };
    write_generated_headers(&hts, &config);

    // The SIMD files get their flags in builds of their own; their objects are
    // linked into the one library.
    for (file, flags) in simd {
        let mut b = cfg.clone();
        for flag in *flags {
            b.flag(flag);
        }
        b.file(hts.join(file));
        for obj in b.compile_intermediates() {
            cfg.object(obj);
        }
    }
    for f in FILES {
        if !simd.iter().any(|(s, _)| s == f) {
            cfg.file(hts.join(f));
        }
    }
    cfg.file("csrc/fgumi_hts.c");
    cfg.compile("fgumi_hts");

    println!("cargo:include={}", hts.display());
    println!("cargo:rustc-link-lib=pthread");
    println!("cargo:rustc-link-lib=m");
}
