//! Queue-memory backpressure from the output side back to the Read step.
//!
//! The threaded BAM pipeline advertises a queue memory budget (`--max-memory`,
//! logged as "Queue memory budget: N total"). Every stage between Read and
//! Write is bounded, but the bound on most of them is a *slot count*, not a
//! byte count — so when the output device stalls, each stage saturates with
//! however many bytes its slots happen to hold and the budget is not what
//! decides the ceiling.
//!
//! Read is the pipeline's only source of new bytes, and nothing downstream
//! waits on it to make progress, so gating Read on the accounted in-flight
//! bytes bounds the whole pipeline without risking deadlock. These tests pin
//! that behaviour: with a writer that never completes, the pipeline must stop
//! pulling input rather than draining the whole file into its queues.
//!
//! See <https://github.com/fulcrumgenomics/fgumi/issues/746>.

